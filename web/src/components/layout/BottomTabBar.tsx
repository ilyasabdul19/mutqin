export function BottomTabBar() {
  const { t } = useTranslation();
  const routerState = useRouterState();
  const currentPath = routerState.location.pathname;

  return (
    <nav
      className="flex h-14 items-center justify-around border-t border-gray-200 bg-white pb-[env(safe-area-inset-bottom)]"
      aria-label={t('nav.home')}
    >
      {tabs.map((tab) => {
        const isActive = tab.to === '/' ? currentPath === '/' : currentPath === tab.to || currentPath.startsWith(tab.to + '/');
        return (
          <Link
            key={tab.key}
            to={tab.to}
            aria-current={isActive ? 'page' : undefined}
            className={`flex flex-1 flex-col items-center gap-0.5 py-1 text-xs font-medium ${
              isActive ? 'text-primary-600' : 'text-gray-500'
            }`}
          >
            {tab.icon}
            <span>{t(tab.label)}</span>
          </Link>
        );
      })}
    </nav>
  );
}
